      SUBROUTINE TRACE_MPI_SUMMARY(NIT)
      INTEGER, INTENT(IN) :: NIT
      REAL(DOUBLE) :: LOCAL_SUMMARY(6), MIN_SUMMARY(6), MAX_SUMMARY(6)
      REAL(DOUBLE) :: SCALE
      CHARACTER(LEN=TRACE_FIELD_LENGTH) :: FIELDS(TRACE_FIELD_COUNT)
      CHARACTER(LEN=512) :: FILE_NAME
      INTEGER :: I, J, RANK_UNIT
      INTEGER(KIND=8) :: FILE_SIZE
      LOGICAL :: MISMATCH

      IF (.NOT.TRACE_ORBOPT) RETURN
      LOCAL_SUMMARY = 0.D0
      DO J = 1, NW
         LOCAL_SUMMARY(1) = LOCAL_SUMMARY(1) + DBLE(J)*E(J)
         LOCAL_SUMMARY(2) = LOCAL_SUMMARY(2) + DBLE(J)*SCNSTY(J)
         LOCAL_SUMMARY(5) = LOCAL_SUMMARY(5) + DBLE(J)*UCF(J)
         DO I = 1, MF(J)
            LOCAL_SUMMARY(3) = LOCAL_SUMMARY(3) + DBLE(I+J)*PF(I,J)
            LOCAL_SUMMARY(4) = LOCAL_SUMMARY(4) + DBLE(I+J)*QF(I,J)
         END DO
      END DO
      IF (ASSOCIATED(EVEC)) THEN
         DO I = 1, SIZE(EVEC)
            LOCAL_SUMMARY(6) = LOCAL_SUMMARY(6) + DBLE(I)*EVEC(I)
         END DO
      ENDIF
      CALL MPI_Allreduce(LOCAL_SUMMARY, MIN_SUMMARY, 6,             &
                         MPI_DOUBLE_PRECISION, MPI_MIN,             &
                         MPI_COMM_WORLD, ierr)
      CALL MPI_Allreduce(LOCAL_SUMMARY, MAX_SUMMARY, 6,             &
                         MPI_DOUBLE_PRECISION, MPI_MAX,             &
                         MPI_COMM_WORLD, ierr)
      MISMATCH = .FALSE.
      DO I = 1, 6
         SCALE = MAX(1.D0, ABS(MIN_SUMMARY(I)), ABS(MAX_SUMMARY(I)))
         IF (ABS(MAX_SUMMARY(I)-MIN_SUMMARY(I)) > 1.D-12*SCALE)    &
            MISMATCH = .TRUE.
      END DO
      IF (.NOT.MISMATCH) RETURN

      WRITE (FILE_NAME,'(A,I3.3,A)') 'orbopt_trace.rank', myid, '.csv'
      IF (LEN_TRIM(ORBOPT_TRACE_DIRECTORY) > 0) FILE_NAME =        &
         TRIM(ORBOPT_TRACE_DIRECTORY)//'/'//TRIM(FILE_NAME)
      INQUIRE(FILE=TRIM(FILE_NAME), SIZE=FILE_SIZE)
      OPEN(NEWUNIT=RANK_UNIT, FILE=TRIM(FILE_NAME), STATUS='UNKNOWN', &
           POSITION='APPEND', ACTION='WRITE')
      IF (FILE_SIZE <= 0) CALL WRITE_TRACE_HEADER(RANK_UNIT)
      DO J = 1, 6
         CALL CLEAR_TRACE_FIELDS(FIELDS, 'mpi_summary_mismatch', NIT)
         CALL PUT_INTEGER(FIELDS(6), J)
         CALL PUT_REAL(FIELDS(39), LOCAL_SUMMARY(J))
         WRITE (FIELDS(40),'(A,ES16.8,A,ES16.8)')                  &
            'min=', MIN_SUMMARY(J), ' max=', MAX_SUMMARY(J)
         CALL EMIT_TRACE_ROW(RANK_UNIT, FIELDS)
      END DO
      CLOSE(RANK_UNIT)
      END SUBROUTINE TRACE_MPI_SUMMARY

      SUBROUTINE CHECK_RELATIVISTIC_PAIRS
      INTEGER :: I, J, L, PARTNER_KAPPA
      LOGICAL :: UNBALANCED, PARTNER_FOUND
      CHARACTER(LEN=TRACE_FIELD_LENGTH) :: FIELDS(TRACE_FIELD_COUNT)

      UNBALANCED = .FALSE.
      DO I = 1, NW
         IF (NAK(I) > 0) THEN
            L = NAK(I)
            PARTNER_KAPPA = -(L + 1)
         ELSE
            L = -NAK(I) - 1
            IF (L == 0) CYCLE
            PARTNER_KAPPA = L
         ENDIF
         PARTNER_FOUND = .FALSE.
         DO J = 1, NW
            IF (NP(J) /= NP(I) .OR. NAK(J) /= PARTNER_KAPPA) CYCLE
            PARTNER_FOUND = .TRUE.
            IF (I > J) EXIT
            IF (LFIX(I) .EQV. LFIX(J)) EXIT
            UNBALANCED = .TRUE.
            IF (myid == 0 .AND. WARN_UNBALANCED_PAIR) THEN
               WRITE (ISTDE,'(A,1X,I0,A,1X,I0,A)')                 &
                  'ORBOPT warning: unbalanced relativistic pair', &
                  NP(I), NH(I), NP(J), NH(J)
            ENDIF
            IF (TRACE_ORBOPT .AND. myid == 0) THEN
               CALL OPEN_ORBOPT_TRACE
               CALL CLEAR_TRACE_FIELDS(FIELDS, 'pair_check', 0)
               CALL PUT_INTEGER(FIELDS(4), I)
               CALL PUT_INTEGER(FIELDS(5), J)
               FIELDS(40) = 'unbalanced_selection'
               CALL EMIT_TRACE_ROW(ORBOPT_TRACE_UNIT, FIELDS)
            ENDIF
            EXIT
         END DO
         IF (PARTNER_FOUND .OR. LFIX(I)) CYCLE
         UNBALANCED = .TRUE.
         IF (myid == 0 .AND. WARN_UNBALANCED_PAIR) THEN
            WRITE (ISTDE,'(A,1X,I0,A,1X,A,I0)')                    &
               'ORBOPT warning: varied orbital has no relativistic partner', &
               NP(I), NH(I), 'expected kappa=', PARTNER_KAPPA
         ENDIF
         IF (TRACE_ORBOPT .AND. myid == 0) THEN
            CALL OPEN_ORBOPT_TRACE
            CALL CLEAR_TRACE_FIELDS(FIELDS, 'pair_check', 0)
            CALL PUT_ORBITAL_FIELDS(FIELDS, I)
            WRITE (FIELDS(40),'(A,I0)') 'missing_partner_kappa=',  &
                                         PARTNER_KAPPA
            CALL EMIT_TRACE_ROW(ORBOPT_TRACE_UNIT, FIELDS)
         ENDIF
      END DO

      IF (UNBALANCED .AND. REQUIRE_BALANCED_PAIR) THEN
         IF (myid == 0) WRITE (ISTDE,'(A)')                        &
            'ORBOPT: set GRASP_REQUIRE_BALANCED_PAIR=0 to continue.'
         ERROR STOP 'ORBOPT: unbalanced relativistic orbitals selected'
      ENDIF
      END SUBROUTINE CHECK_RELATIVISTIC_PAIRS

