         CALL PUT_ORBITAL_GROUP(FIELDS(7), J)
         CALL PUT_INTEGER(FIELDS(10), NAKJ)
         CALL PUT_REAL(FIELDS(19), E(J))
         CALL EMIT_TRACE_ROW(ORBOPT_TRACE_UNIT, FIELDS)
      END DO
      END SUBROUTINE TRACE_ORTHY_ORDER

