      IF (.NOT.TRACE_OPEN) RETURN
      TRACE_NIT = NIT
      IF (TRACE_NIT == 0) TRACE_NIT = ORBOPT_ITERATION
      DO I = 1, KTOTAL
         J = KINDX(I)
